    [Theory]
    [InlineData(null, null)]
    [InlineData("", "")]
    [InlineData("Quantum-abc123.db", "Quantum-abc123.db")]
    [InlineData("Server=h;Database=d;Uid=u;Pwd=topsecret;", "Server=h;Database=d;Uid=u;Pwd=***;")]
    [InlineData("Password=topsecret", "Password=***")]
    [InlineData("Server=h;Pwd=topsecret", "Server=h;Pwd=***")]
    // 畸形/任意串：只打码能识别的键值段，其余原样返回，绝不抛异常
    [InlineData(";;;Pwd=x;;=", ";;;Pwd=***;;=")]
    [InlineData("不是连接串", "不是连接串")]
    [InlineData("key=value;Pwd", "key=value;Pwd")]
    // 前端拼串对含 ; 的取值用双引号包裹：引号内的 ; 不是分段符，整值必须一起打码
    [InlineData("Server=h;Pwd=\"a;b;c\";CharSet=utf8", "Server=h;Pwd=***;CharSet=utf8")]
    [InlineData("Server=h;Pwd=\"a;b\";Database=d", "Server=h;Pwd=***;Database=d")]
    // 未闭合引号（畸形串）：引号内的一切都随该段一起打码，尾部没有残段可漏
    [InlineData("Server=h;Pwd=\"a;b;c", "Server=h;Pwd=***")]
    // 逗号不是连接串分隔符：引号闭合后紧跟的 ,Database=d 仍属同一段，一并被吃掉（无泄露）
    [InlineData("Server=h;Pwd=\"\",Database=d", "Server=h;Pwd=***")]
    // 引号闭合后确有 `;`：后续段不是密码，正常保留（其内容不含密码片段）
    [InlineData("Pwd=\"a\";tail", "Pwd=***;tail")]
    public void MaskConnectionString_MasksSecretKeysAndNeverThrows(string input, string expected)
    {
        Assert.Equal(expected, SetupService.MaskConnectionString(input));
    }

    [Theory]
    [InlineData("Server=h;Pwd=\"secret;tail\";Database=d", "secret")]
    [InlineData("Server=h;Pwd=\"secret;tail\";Database=d", "tail")]
    [InlineData("Pwd=\"sec;ret\";x", "sec")]
    public void MaskConnectionString_QuotedPasswordContainingSemicolon_LeaksNoFragment(string input, string secretFragment)
