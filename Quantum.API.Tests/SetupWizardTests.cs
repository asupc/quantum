    [Fact]
    public void SeedSelectedTasks_IsIdempotent_AndPreservesRuntimeEdits()
    {
        WriteScript("a.cs", ValidScript + "\n// 原始");
        using var connectionAndDb = new TestDatabase();
        var service = new SetupService(connectionAndDb.Db, _sourceDir, _runtimeDir);

        Assert.Equal(1, service.SeedSelectedTasks(new[] { "a.cs" }));
        Assert.True(service.SeedSelectedTasks(new[] { "a.cs" }) == 0, "重复播种同名脚本应跳过");

        var runtimePath = Path.Combine(_runtimeDir, "a.cs");
        File.WriteAllText(runtimePath, ValidScript + "\n// 本地修改");
        Assert.True(service.SeedSelectedTasks(null) == 0, "全量播种也不覆盖运行目录已改动脚本");
        Assert.Equal(ValidScript + "\n// 本地修改", File.ReadAllText(runtimePath));
        Assert.Single(connectionAndDb.Db.Tasks.AsNoTracking().ToList());
    }

