// 历史库图标名 → FA class；未命中时回退为通用圆点图标并 console 提示
export function faIcon(name) {
    if (!name) return 'fa-solid fa-circle'
    const mapped = iconMap[name]
    if (!mapped) {
        console.warn(`[icons] 未映射的历史库图标: ${name}`)
        return 'fa-solid fa-circle'
    }
    return mapped
}
